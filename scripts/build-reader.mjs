// Builds the reader WebView page: foliate-js + src/features/reader/web/bridge.js bundled into one
// inline script, the Literata faces embedded as data blocks, and a Content-Security-Policy that
// only allows that exact script (by hash). Section frames are blob: documents, which inherit the
// policy, so scripts inside EPUBs never run and nothing can load from the network.
//
// Run `npm run build:reader` after changing bridge.js or updating src/vendor/foliate-js.
// The output is committed so app builds don't need esbuild.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const webDir = join(root, 'src/features/reader/web');

// Formats and features view.js can load dynamically but OwnBooks doesn't ship.
const UNUSED = /\/(pdf|mobi|fb2|comic-book|search|tts)\.js$|\/vendor\/fflate\.js$/;

const result = await build({
  entryPoints: [join(webDir, 'bridge.js')],
  bundle: true,
  write: false,
  format: 'iife',
  minify: true,
  legalComments: 'none',
  target: 'chrome110',
  plugins: [
    {
      name: 'stub-unused-formats',
      setup(b) {
        b.onResolve({ filter: UNUSED }, (args) => ({ path: args.path, namespace: 'unused' }));
        b.onLoad({ filter: /.*/, namespace: 'unused' }, () => ({
          contents: 'throw new Error("This format is not supported in OwnBooks")',
          loader: 'js',
        }));
      },
    },
  ],
});

const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const hash = createHash('sha256').update(script).digest('base64');

const fonts = [
  ['400Regular', '400', 'normal'],
  ['400Regular_Italic', '400', 'italic'],
  ['700Bold', '700', 'normal'],
  ['700Bold_Italic', '700', 'italic'],
]
  .map(([name, weight, style]) => {
    const file = join(root, `node_modules/@expo-google-fonts/literata/${name}/Literata_${name}.ttf`);
    const data = readFileSync(file).toString('base64');
    return `<script type="application/x-font" data-weight="${weight}" data-style="${style}">${data}</script>`;
  })
  .join('');

const csp = [
  "default-src 'none'",
  `script-src 'sha256-${hash}'`,
  "style-src 'unsafe-inline' blob:",
  'img-src blob: data:',
  'font-src blob: data:',
  'media-src blob: data:',
  'connect-src file: blob: data:',
  'frame-src blob: about:',
  'child-src blob:',
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');

const html =
  '<!doctype html><html><head><meta charset="utf-8">' +
  '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">' +
  `<meta http-equiv="Content-Security-Policy" content="${csp}">` +
  '<style>html,body{margin:0;height:100%;overflow:hidden;-webkit-tap-highlight-color:transparent}' +
  'foliate-view{display:block;height:100%}</style>' +
  fonts +
  `</head><body><script>${script}</script></body></html>`;

const out = join(webDir, 'readerHtml.generated.ts');
writeFileSync(
  out,
  '// Generated by scripts/build-reader.mjs. Do not edit.\n' +
    `export const READER_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`Wrote ${out} (${Math.round(html.length / 1024)} KB, script ${Math.round(script.length / 1024)} KB)`);
